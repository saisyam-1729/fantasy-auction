/**
 * Build the ILT20 2026 player lists from the squad spreadsheet, for both formats:
 *   - auction: public.player_inventory, inventory_type 'ILT20_2026' (base price in rupees)
 *   - draft:   public.draft_pool_players, pool 'ILT20_2026'
 *
 *   node scripts/import-ilt20-2026.cjs <path to ILT20_2026_Squads_Roles_BasePrice.xlsx>
 *
 * Reads the "All Players" sheet (#, Team, Player, Captain, Wildcard, Role, Role Confidence,
 * Base Price, Base Price (₹ Lakh)) and writes supabase/ilt20_2026_seed.generated.sql.
 * Both inserts upsert, so re-running after squad changes keeps rooms that already use them.
 */
const fs = require('fs')
const path = require('path')
const XLSX = require('xlsx')

const KEY = 'ILT20_2026'
const LAKH = 100_000
const file = process.argv[2]
if (!file) {
  console.error('Usage: node scripts/import-ilt20-2026.cjs <ILT20_2026_Squads_Roles_BasePrice.xlsx>')
  process.exit(1)
}

const sheet = XLSX.readFile(file).Sheets['All Players']
if (!sheet) throw new Error('Sheet "All Players" not found')
const rows = XLSX.utils.sheet_to_json(sheet, { defval: null })

const clean = (v) => (v == null ? null : String(v).replace(/\s+/g, ' ').trim() || null)
const sql = (v) => (v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`)
// auction player_type codes used by the auction room (squad roles, filters, sets)
const TYPE = { Batter: 'BAT', 'WK-Batter': 'WK', 'All-rounder': 'ALL', Bowler: 'BOWL' }

const auction = []
const draft = []
const seen = new Set()
for (const r of rows) {
  const team = clean(r.Team)
  const name = clean(r.Player)
  const no = Number(r['#'])
  if (!team || !name || !Number.isInteger(no)) continue
  const k = `${team}|${name}`.toLowerCase()
  if (seen.has(k)) continue
  seen.add(k)

  const role = clean(r.Role)
  const lakh = Number(r['Base Price (₹ Lakh)'])
  if (!Number.isFinite(lakh) || lakh <= 0) throw new Error(`No base price for ${name}`)
  const captain = clean(r.Captain)
  const wildcard = /^yes$/i.test(clean(r.Wildcard) ?? '')
  const notes = [wildcard ? 'Wildcard' : null, clean(r['Role Confidence']) === 'Low' && role !== 'Unknown' ? 'Role unconfirmed' : null]
    .filter(Boolean)
    .join('. ') || null

  auction.push(`  (${sql(KEY)}, ${sql('ilt20-2026-' + no)}, ${sql(name)}, ${sql(TYPE[role] ?? 'UNK')}, ${Math.round(lakh * LAKH)}, ${sql(team)})`)
  draft.push(`  (${sql(KEY)}, ${no}, ${sql(team)}, ${sql(name)}, ${sql(role === 'Unknown' ? null : role)}, ${sql(captain)}, ${sql(notes)})`)
}

const out = `-- Generated by scripts/import-ilt20-2026.cjs from ILT20_2026_Squads_Roles_BasePrice.xlsx. Do not edit by hand.
-- ${auction.length} players. Base prices are the sheet's own INR tiers (not official ILT20 prices).
-- Run after supabase/draft.sql.

-- Auction format
INSERT INTO public.player_inventory (inventory_type, player_id, player_name, player_type, base_price, team) VALUES
${auction.join(',\n')}
ON CONFLICT (inventory_type, player_id) DO UPDATE SET
  player_name = EXCLUDED.player_name,
  player_type = EXCLUDED.player_type,
  base_price = EXCLUDED.base_price,
  team = EXCLUDED.team;

-- Draft format
INSERT INTO public.draft_pool_players (pool, sort_no, team, player_name, role, captain, notes) VALUES
${draft.join(',\n')}
ON CONFLICT (pool, team, player_name) DO UPDATE
SET sort_no = EXCLUDED.sort_no, role = EXCLUDED.role, captain = EXCLUDED.captain, notes = EXCLUDED.notes;
`
const target = path.join(__dirname, '..', 'supabase', 'ilt20_2026_seed.generated.sql')
fs.writeFileSync(target, out)
console.log(`Wrote ${auction.length} players to ${path.relative(process.cwd(), target)}`)
