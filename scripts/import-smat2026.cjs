/**
 * Build the SMAT 2026 draft pool seed from the squad spreadsheet.
 *
 *   node scripts/import-smat2026.cjs <path to SMAT_2026_27_Players.xlsx>
 *
 * Reads the "All Players" sheet (#, Team, Player, Captain / VC, Role, Notes) and writes
 * supabase/draft_pool_smat2026_seed.generated.sql. The seed upserts on (pool, team, name),
 * so it can be re-run when squads change without breaking drafts that already picked.
 */
const fs = require('fs')
const path = require('path')
const XLSX = require('xlsx')

const POOL = 'SMAT_2026'
const file = process.argv[2]
if (!file) {
  console.error('Usage: node scripts/import-smat2026.cjs <SMAT_2026_27_Players.xlsx>')
  process.exit(1)
}

const wb = XLSX.readFile(file)
const sheet = wb.Sheets['All Players']
if (!sheet) throw new Error('Sheet "All Players" not found')
const rows = XLSX.utils.sheet_to_json(sheet, { defval: null })

const clean = (v) => (v == null ? null : String(v).replace(/\s+/g, ' ').trim() || null)
const sql = (v) => (v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`)

const seen = new Set()
const values = []
for (const r of rows) {
  const team = clean(r.Team)
  const name = clean(r.Player)
  if (!team || !name) continue
  const key = `${team}|${name}`.toLowerCase()
  if (seen.has(key)) continue
  seen.add(key)

  let role = clean(r.Role)
  let notes = clean(r.Notes)
  if (role === 'Not specified') role = null
  if (role === 'Standby') {
    role = null
    notes = notes ? `Standby. ${notes}` : 'Standby'
  }
  if (role === 'Batter (WK)') role = 'Wicketkeeper'
  const captain = clean(r['Captain / VC'])
  values.push(`  (${sql(POOL)}, ${Number(r['#']) || values.length + 1}, ${sql(team)}, ${sql(name)}, ${sql(role)}, ${sql(captain)}, ${sql(notes)})`)
}

const out = `-- Generated by scripts/import-smat2026.cjs from SMAT_2026_27_Players.xlsx. Do not edit by hand.
-- ${values.length} players. Run after supabase/draft.sql.
INSERT INTO public.draft_pool_players (pool, sort_no, team, player_name, role, captain, notes) VALUES
${values.join(',\n')}
ON CONFLICT (pool, team, player_name) DO UPDATE
SET sort_no = EXCLUDED.sort_no, role = EXCLUDED.role, captain = EXCLUDED.captain, notes = EXCLUDED.notes;
`
const target = path.join(__dirname, '..', 'supabase', 'draft_pool_smat2026_seed.generated.sql')
fs.writeFileSync(target, out)
console.log(`Wrote ${values.length} players to ${path.relative(process.cwd(), target)}`)
